"""Freeze a LUT + one global tree + gated wall trees into the existing runtime."""
import argparse
import json
import math
import numpy as np
import lightgbm as lgb
from displacement_compact import compact_features
from displacement_residual import FEATURES, architecture, make_features, indices
from displacement_analyze import OUT, describe
from displacement_assets import sha
from project_paths import BUILD, REPO_ROOT


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--model',default='stage10_hybrid127')
    ap.add_argument('--name',default='stage10_hybrid1')
    ap.add_argument('--global-trees',type=int,default=1)
    ap.add_argument('--wall-trees',type=int,default=64)
    ap.add_argument('--quick',action='store_true')
    ap.add_argument('--fixed',action='store_true',help='Quantize LUT values to 1/256 ps for integer summation')
    args=ap.parse_args()
    config=json.loads((REPO_ROOT/'docs'/(args.model+'.json')).read_text())
    lutname=config['lut'];lm=json.loads((REPO_ROOT/'docs'/(lutname+'.json')).read_text())
    tables=np.load(OUT/(lutname+'.npz'))
    gm=lgb.Booster(model_file=str(OUT/(args.model+'_global.txt')))
    wm=lgb.Booster(model_file=str(OUT/(args.model+'_wall.txt')))
    fn=FEATURES+['bound','base_minus_bound','lut_minus_base']
    assert gm.feature_name()==wm.feature_name()==fn
    meta=json.loads((BUILD/'architecture_meta.json').read_text())
    enc=json.loads((REPO_ROOT/'docs/stage9_bound_encoding.json').read_text())
    names,family,bit,_,_,_,_,dd=architecture()
    sm={p:i for i,p in enumerate(meta['sources'])};tm={p:i for i,p in enumerate(meta['targets'])}
    lines=['// Generated by displacement_hybrid_export.py; do not edit.','#pragma once',
           '#define EST_RESIDUAL_DIRECT 1','#define EST_RESIDUAL_PREPARE 1',
           f'constexpr int RFeatures={len(fn)}, RTrees=0, RSourceCount=208, RTargetCount=288;',
           'constexpr bool RClamp=true;',f'constexpr unsigned RTableCRC={enc["table_crc32"]}u;',
           f'constexpr unsigned long RDecodedBytes={enc["decoded_stream_bytes"]}ul;',
           'using RFeature=int32_t;']
    lines += [f'constexpr int RF_{name}={i};' for i,name in enumerate(fn)]
    for name,values in [('RFamily',family),('RBit',bit),('RSourceIndex',[sm.get(i,-1) for i in range(len(names))]),
                        ('RTargetIndex',[tm.get(i,-1) for i in range(len(names))]),('RDoorDistance',dd)]:
        lines.append('static const int '+name+'[]={'+','.join(map(str,values))+'};')
    lines.append('static const int RSlopes[4][2]='+json.dumps(meta['slopes_scaled12']).replace('[','{').replace(']','}')+';')
    table_values=[tables['table'+str(i)].copy() for i in range(len(lm['definitions']))]
    if args.fixed:
        table_values=[np.rint(a*256).astype(np.int32)/256 for a in table_values]
    for i,a in enumerate(table_values):
        dtype='int32_t' if args.fixed else 'double'
        values=','.join(str(int(z*256)) if args.fixed else format(z,'.17g') for z in a)
        lines.append(f'static const {dtype} CLut{i}[]={{'+values+'};')
    usedbins=sorted({k[:-4] for term in lm['definitions'] for k in term if k.endswith('_bin')})
    binranges=dict(margin=(-64,512),distance=(0,668),base=(0,10000),ax=(0,119),rx=(-160,160),ry=(-600,600),landing_door_distance=(0,50))
    for key in usedbins:
        lo,hi=binranges[key];vv=np.searchsorted(lm['bins'][key],np.arange(lo,hi+1),side='left')
        lines += [f'static const unsigned char CBin_{key}[]={{'+','.join(map(str,vv))+'};']
    lines += ['static void rPrepareFeature(RFeature* f) {']
    for key in usedbins:
        lo,hi=binranges[key];expr='f[RF_base_minus_bound]' if key=='margin' else 'f[RF_'+key+']'
        lines.append(f'    int c_{key}_bin=CBin_{key}[max({lo},min({hi},{expr}))-({lo})];')
    lines.append('    '+('int' if args.fixed else 'double')+' delta=0;')
    for i,(term,shape) in enumerate(zip(lm['definitions'],lm['shapes'])):
        expr='0'
        for k,n in zip(term,shape):
            val='c_'+k if k.endswith('_bin') else 'f[RF_'+k+']'
            expr=f'(({expr})*{n}+{val})'
        lines.append(f'    delta+=CLut{i}[{expr}];')
    rounding='f[RF_base]+((delta+128)>>8)' if args.fixed else '(int)floor(f[RF_base]+delta+.5)'
    lines += [f'    f[RF_lut_minus_base]=max(f[RF_bound],max(0,{rounding}))-f[RF_base];','}']
    used=set()
    def branch(node,indent):
        if 'leaf_value' in node:return [indent+'return '+format(node['leaf_value'],'.17g')+';']
        fid=node['split_feature'];used.add(fn[fid]);v=f'f[{fid}]'
        if node['decision_type']=='==':
            members=list(map(int,node['threshold'].split('||')))
            words=[0]*(max(members)//64+1)
            for m in members:words[m//64]|=1<<(m%64)
            cond=' || '.join(f'((unsigned){v}/64=={i}u && (({w}ull>>((unsigned){v}&63))&1ull))' for i,w in enumerate(words) if w)
        else:cond=v+'<='+str(math.floor(float(node['threshold'])))
        return [indent+'if('+cond+') {']+branch(node['left_child'],indent+'    ')+[indent+'} else {']+branch(node['right_child'],indent+'    ')+[indent+'}']
    for prefix,model,n in [('G',gm,args.global_trees),('W',wm,args.wall_trees)]:
        for i,t in enumerate(model.dump_model(num_iteration=n)['tree_info']):
            lines += [f'static double c{prefix}{i}(const RFeature* f) {{']+branch(t['tree_structure'],'    ')+['}']
    lines += ['static double rDirectPredict(const RFeature* f) {','    double delta=0;', '    if(f[RF_landing_wall]) {']
    lines += [f'        delta+=cW{i}(f);' for i in range(args.wall_trees)]
    lines += ['    } else {','        delta=f[RF_lut_minus_base];']
    lines += [f'        delta+=cG{i}(f);' for i in range(args.global_trees)]
    lines += ['    }','    return delta;','}',
              'static void rBatchPredict(const RFeature* f,double* delta,int n) {for(int i=0;i<n;i++) delta[i]=rDirectPredict(f+(size_t)i*RFeatures); }']
    if args.quick:
        # Ordinary requests never construct the 56-element feature tile. Keep
        # only global-tree and LUT dependencies, and prefetch their envelope.
        quickused=set()
        def scan(n):
            if 'split_feature' in n:
                quickused.add(fn[n['split_feature']]);scan(n['left_child']);scan(n['right_child'])
        for t in gm.dump_model(num_iteration=args.global_trees)['tree_info']:scan(t['tree_structure'])
        required=quickused | {k[:-4] if k.endswith('_bin') else k for term in lm['definitions'] for k in term}
        exprs=dict(sx='sx',sy='sy',tx='tx',ty='ty',dx='dx',dy='dy',ax='abs(dx)',ay='abs(dy)',distance='abs(dx)+abs(dy)',
                   source='source',target='target',rx='dx-ndx',ry='dy-ndy',rax='abs(dx-ndx)',ray='abs(dy-ndy)',
                   base='base',bound='bound',base_minus_bound='base-bound',base_minus_gap='base-ngx-ngy',
                   cross='(sx<=75 && tx>=90)||(tx<=75 && sx>=90)',
                   landing_cross='(lx<=75 && tx>=90)||(tx<=75 && lx>=90)',
                   landing_wall='0',landing_door_distance='RDoorDistance[ly]',source_door_distance='RDoorDistance[sy]',target_door_distance='RDoorDistance[ty]',
                   source_phase='sy%100',target_phase='ty%100',direction='2*(dx<0)+(dy<0)',gap_y='hpre[max(sy,ty)]-hpre[min(sy,ty)]',
                   net_gap_x='ngx',net_gap_y='ngy',overy='max(abs(dy-ndy)-abs(dy),0)',overx='max(abs(dx-ndx)-abs(dx),0)',
                   source_family='RFamily[source]',target_family='RFamily[target]',rx_mod='((dx-ndx)%10+10)%10',ry_mod='((dy-ndy)%12+12)%12',
                   source_bit='RBit[source]',target_bit='RBit[target]',edge_x='min(min(sx,tx),119-max(sx,tx))',edge_y='min(min(sy,ty),549-max(sy,ty))')
        lines += ['#define EST_RESIDUAL_QUICK 1',
                  'static inline size_t cBoundIndex(int sx,int sy,int tx,int ty,int source,int target) {',
                  '    int dx=tx-sx,dy=ty-sy,mx=(dx%10+10)%10,my=(dy%12+12)%12;',
                  '    return (((size_t)RSourceIndex[source]*288+RTargetIndex[target])*120+mx*12+my)*4;', '}',
                  'static inline void rQuickPrefetch(int sx,int sy,int tx,int ty,int source,int target) {',
                  '    if(RSourceIndex[source]>=0 && RTargetIndex[target]>=0) __builtin_prefetch(&RBoundTable[cBoundIndex(sx,sy,tx,ty,source,target)],0,3);','}',
                  'static bool rQuickPredict(int sx,int sy,int tx,int ty,int source,int target,long base,double& output) {',
                  '    int ndx=netdx[source],ndy=netdy[source],lx=sx+ndx,ly=sy+ndy;',
                  '    if(lx>=76 && lx<=89 && RDoorDistance[ly]>0) return false;',
                  '    int dx=tx-sx,dy=ty-sy,mx=(dx%10+10)%10,my=(dy%12+12)%12;',
                  '    int ngx=vpre[max(sx,lx)]-vpre[min(sx,lx)]+vpre[max(lx,tx)]-vpre[min(lx,tx)];',
                  '    int ngy=hpre[max(sy,ly)]-hpre[min(sy,ly)]+hpre[max(ly,ty)]-hpre[min(ly,ty)];',
                  '    const int16_t* q=&RBoundTable[cBoundIndex(sx,sy,tx,ty,source,target)];',
                  '    int xx=125*((dx-mx)/10),yp=127*((dy-my)/12),ym=-125*((dy-my)/12);',
                  '    int bound=max(max(q[0]+xx+yp,q[1]+xx+ym),max(q[2]-xx+yp,q[3]-xx+ym));',
                  '    bound+=ngx+ngy;', '    RFeature f[RFeatures];']
        for key in sorted(required-{'margin','lut_minus_base'}):
            lines.append('    f[RF_'+key+']='+exprs[key]+';')
        for key in usedbins:
            lo,hi=binranges[key];expr='base-bound' if key=='margin' else 'f[RF_'+key+']'
            lines.append(f'    int c_{key}_bin=CBin_{key}[max({lo},min({hi},(int)({expr})))-({lo})];')
        lines.append('    '+('int correction=0;' if args.fixed else 'double correction=0;'))
        for i,(term,shape) in enumerate(zip(lm['definitions'],lm['shapes'])):
            expr='0'
            for k,n in zip(term,shape):
                val='c_'+k if k.endswith('_bin') else 'f[RF_'+k+']'
                expr=f'(({expr})*{n}+{val})'
            lines.append(f'    correction+=CLut{i}[{expr}];')
        rounding='(int)base+((correction+128)>>8)' if args.fixed else '(int)floor(base+correction+.5)'
        lines += [f'    int lut=max(bound,max(0,{rounding}));',
                  '    f[RF_lut_minus_base]=lut-base;', '    double delta=0;']
        lines += [f'    delta+=cG{i}(f);' for i in range(args.global_trees)]
        lines += ['    output=max(bound,max(0,(int)(lut+delta+.5)));','    return true;','}']
    header=OUT/(args.name+'.hpp');header.write_text('\n'.join(lines)+'\n')
    frozen=dict(candidate=args.name,model=args.model,lut=lutname,global_trees=args.global_trees,wall_trees=args.wall_trees,quick=args.quick,fixed_lut=args.fixed,
                model_sha256=sha(OUT/(args.model+'_global.txt')),wall_sha256=sha(OUT/(args.model+'_wall.txt')),
                lut_sha256=sha(OUT/(lutname+'.npz')),header_sha256=sha(header),used_tree_features=sorted(used))
    (OUT/(args.name+'_frozen.json')).write_text(json.dumps(frozen,indent=2)+'\n')
    g=np.load(OUT/'geometry.npz');base=np.load(OUT/'displacement_cal16_prediction.npy')
    v,bound,_=compact_features(g,base);delta=np.zeros(len(base))
    for i,(term,shape) in enumerate(zip(lm['definitions'],lm['shapes'])):
        k=np.zeros(len(base),np.int64)
        for col,n in zip(term,shape):k=k*n+v[col]
        delta+=table_values[i][k]
    lut=np.maximum(bound,np.maximum(0,np.floor(base+delta+.5))).astype(np.int32)
    x=make_features(g,base);x['bound']=bound.astype(np.float32);x['base_minus_bound']=(base-bound).astype(np.float32);x['lut_minus_base']=(lut-base).astype(np.float32)
    wall=x.landing_wall.to_numpy()>0
    pred=lut.astype(float)+gm.predict(x,num_iteration=args.global_trees,num_threads=6)
    pred[wall]=base[wall]+wm.predict(x.iloc[np.flatnonzero(wall)],num_iteration=args.wall_trees,num_threads=6)
    pred=np.maximum(bound,np.maximum(0,np.floor(pred+.5))).astype(np.int32)
    _,_,_,ndx,ndy,_,_,_=architecture()
    good=(g['sx']+ndx[g['source_id']]>=0)&(g['sx']+ndx[g['source_id']]<120)&(g['sy']+ndy[g['source_id']]>=0)&(g['sy']+ndy[g['source_id']]<550)
    pred[~good]=base[~good]
    selfq=(g['sx']==g['tx'])&(g['sy']==g['ty'])&(g['source_id']==g['target_id']);pred[selfq]=0
    np.save(OUT/(args.name+'_reference.npy'),pred)
    _,va,te,held=indices(g)
    frozen.update(valid=describe(g['y'][va],pred[va]),test=describe(g['y'][te],pred[te]),position_assess=describe(g['y'][held],pred[held]),
                  caveat='Historical regression; only new residual excludes held source coordinates')
    (REPO_ROOT/'docs'/(args.name+'_export.json')).write_text(json.dumps(frozen,indent=2)+'\n')
    print(json.dumps(frozen,indent=2),flush=True)


if __name__=='__main__':main()
