"""Export a frozen LightGBM prefix, metadata, and reference predictions for C++."""
import argparse
import json
import lightgbm as lgb
import numpy as np
from displacement_residual import FEATURES, architecture, make_features, architecture_bound, corrected, indices
from displacement_analyze import OUT, describe
from displacement_assets import sha
from project_paths import BUILD, REPO_ROOT


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('model')
    parser.add_argument('--trees', type=int, required=True)
    parser.add_argument('--name', required=True)
    parser.add_argument('--clamp', action='store_true')
    parser.add_argument('--direct', action='store_true', help='Emit C++ branches for frozen trees')
    args = parser.parse_args()
    model_path = OUT / (args.model+'.txt')
    model = lgb.Booster(model_file=str(model_path))
    feature_names = model.feature_name()
    assert feature_names == FEATURES+['bound', 'base_minus_bound']
    dump = model.dump_model(num_iteration=args.trees)
    nodes, roots, categories = [], [], []
    def visit(node):
        index = len(nodes)
        nodes.append(None)
        if 'leaf_value' in node:
            nodes[index] = (-1, -1, -1, float(node['leaf_value']), 0, 0)
            return index
        cb, count = len(categories), 0
        value = 0.
        if node['decision_type'] == '==':
            members = list(map(int, node['threshold'].split('||')))
            words = [0]*(max(members)//64+1)
            for member in members:
                words[member//64] |= 1 << (member%64)
            count = len(words)
            categories.extend(words)
        else:
            assert node['decision_type'] == '<='
            value = float(node['threshold'])
        left, right = visit(node['left_child']), visit(node['right_child'])
        nodes[index] = (left, right, node['split_feature'], value, cb, count)
        return index
    for tree in dump['tree_info']:
        roots.append(visit(tree['tree_structure']))
    assert len(roots) == args.trees
    meta = json.loads((BUILD / 'architecture_meta.json').read_text())
    encoding = json.loads((REPO_ROOT / 'docs/stage9_bound_encoding.json').read_text())
    names, family, bit, _, _, _, _, door_distance = architecture()
    sm, tm = {p:i for i,p in enumerate(meta['sources'])}, {p:i for i,p in enumerate(meta['targets'])}
    lines = ['// Generated by displacement_residual_export.py; do not edit.', '#pragma once',
             f'constexpr int RFeatures={len(feature_names)}, RTrees={args.trees}, RSourceCount=208, RTargetCount=288;',
             f'constexpr bool RClamp={str(args.clamp).lower()};',
             f'constexpr unsigned RTableCRC={encoding["table_crc32"]}u;',
             f'constexpr unsigned long RDecodedBytes={encoding["decoded_stream_bytes"]}ul;',
             'struct RNode {int left,right,feature; double value; unsigned cb,count;};']
    lines += [f'constexpr int RF_{name}={i};' for i, name in enumerate(feature_names)]
    for name, values in [('RFamily', family), ('RBit', bit), ('RSourceIndex', [sm.get(i,-1) for i in range(len(names))]),
                         ('RTargetIndex', [tm.get(i,-1) for i in range(len(names))]), ('RDoorDistance', door_distance)]:
        lines.append('static const int '+name+'[]={'+','.join(map(str, values))+'};')
    lines.append('static const int RSlopes[4][2]='+json.dumps(meta['slopes_scaled12']).replace('[','{').replace(']','}')+';')
    lines.append('static const RNode RNodes[]={')
    lines += ['{'+f'{a},{b},{f},{v:.17g},{cb},{count}'+'},' for a,b,f,v,cb,count in nodes]
    lines += ['};', 'static const int RRoots[]={'+','.join(map(str, roots))+'};',
              'static const uint64_t RCategories[]={'+(','.join(str(v)+'ull' for v in categories) or '0')+'};']
    if args.direct:
        lines.append('#define EST_RESIDUAL_DIRECT 1')
        def branch(at, indent='    '):
            left, right, feature, value, cb, count = nodes[at]
            if left < 0:
                return [indent+f'return {value:.17g};']
            if count:
                condition = f'rCategory(f[{feature}], {cb}u, {count}u)'
            else:
                condition = f'f[{feature}] <= {value:.17g}'
            return ([indent+'if ('+condition+') {']+branch(left, indent+'    ')+
                    [indent+'} else {']+branch(right, indent+'    ')+[indent+'}'])
        lines += ['static inline bool rCategory(float value,unsigned begin,unsigned count) {',
                  '    unsigned cat=(unsigned)(int)value;',
                  '    return cat/64<count && ((RCategories[begin+cat/64]>>(cat&63))&1ull);', '}']
        for t, root in enumerate(roots):
            lines += [f'static double rTree{t}(const float* f) {{']+branch(root)+['}']
        lines += ['static double rDirectPredict(const float* f) {', '    double delta=0;']
        lines += [f'    delta+=rTree{t}(f);' for t in range(len(roots))]
        lines += ['    return delta;', '}']
    header = OUT / (args.name+'.hpp')
    header.write_text('\n'.join(lines)+'\n')
    # Freeze configuration before looking at the historical test regression.
    config = dict(candidate=args.name, model=args.model, model_sha256=sha(model_path), trees=args.trees,
                  bound_clamp=args.clamp, feature_names=feature_names, nodes=len(nodes),
                  header_sha256=sha(header), bound_sha256=encoding['compressed_sha256'])
    config['direct_cpp_branches'] = args.direct
    (OUT / (args.name+'_frozen.json')).write_text(json.dumps(config, indent=2)+'\n')
    g = np.load(OUT / 'geometry.npz')
    base = np.load(OUT / 'displacement_cal16_prediction.npy')
    x = make_features(g, base)
    bound = architecture_bound(g, x)
    x['bound'] = bound.astype(np.float32)
    x['base_minus_bound'] = base-x['bound'].to_numpy()
    pred = corrected(base, model.predict(x, num_iteration=args.trees, num_threads=6))
    if args.clamp:
        pred = np.maximum(pred, bound).astype(np.int32)
    # Match deployment eligibility, including the official zero-delay self rule.
    _, _, _, ndx, ndy, _, _, _ = architecture()
    self_query = ((g['sx']==g['tx']) & (g['sy']==g['ty']) & (g['source_id']==g['target_id']))
    valid_landing = ((g['sx']+ndx[g['source_id']]>=0) & (g['sx']+ndx[g['source_id']]<120) &
                     (g['sy']+ndy[g['source_id']]>=0) & (g['sy']+ndy[g['source_id']]<550))
    pred[~valid_landing] = base[~valid_landing]
    pred[self_query] = 0
    np.save(OUT / (args.name+'_reference.npy'), pred)
    _, valid, test, assess = indices(g)
    config.update(valid=describe(g['y'][valid], pred[valid]), test=describe(g['y'][test], pred[test]),
                  position_assess=describe(g['y'][assess], pred[assess]), full_public=describe(g['y'],pred),
                  caveat='Historical regression slices; new residual excludes held source coordinates, inherited stage8 does not')
    (REPO_ROOT / 'docs' / (args.name+'_export.json')).write_text(json.dumps(config, indent=2)+'\n')
    print(json.dumps({k:config[k] for k in ('candidate','trees','valid','test','position_assess')}, indent=2), flush=True)


if __name__ == '__main__':
    main()
