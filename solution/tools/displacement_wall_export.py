"""Export a sparse wall-only model and its independent Python predictions."""
import argparse
import json
import math
import lightgbm as lgb
import numpy as np
from displacement_analyze import OUT, describe
from displacement_residual import FEATURES, architecture, make_features, indices
from displacement_assets import sha
from project_paths import REPO_ROOT


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('model');ap.add_argument('--base',required=True)
    ap.add_argument('--trees',type=int,required=True);ap.add_argument('--name',required=True)
    args=ap.parse_args();path=OUT/(args.model+'.txt')
    model=lgb.Booster(model_file=str(path));assert model.feature_name()==FEATURES
    names,family,bit,_,_,_,_,dd=architecture()
    lines=['// Generated by displacement_wall_export.py; do not edit.','#pragma once',
           f'constexpr int WFeatures={len(FEATURES)};']
    lines += [f'constexpr int WF_{name}={i};' for i,name in enumerate(FEATURES)]
    for name,values in [('WFamily',family),('WBit',bit),('WDoorDistance',dd)]:
        lines.append('static const int '+name+'[]={'+','.join(map(str,values))+'};')
    def branch(node,indent):
        if 'leaf_value' in node:return [indent+'return '+format(node['leaf_value'],'.17g')+';']
        v=f'f[{node["split_feature"]}]'
        if node['decision_type']=='==':
            members=list(map(int,node['threshold'].split('||')))
            words=[0]*(max(members)//64+1)
            for m in members:words[m//64]|=1<<(m%64)
            cond=' || '.join(f'((unsigned){v}/64=={i}u && (({w}ull>>((unsigned){v}&63))&1ull))' for i,w in enumerate(words) if w)
        else:
            assert node['decision_type']=='<='
            cond=v+'<='+str(math.floor(float(node['threshold'])))
        return [indent+'if('+cond+') {']+branch(node['left_child'],indent+'    ')+[indent+'} else {']+branch(node['right_child'],indent+'    ')+[indent+'}']
    for i,t in enumerate(model.dump_model(num_iteration=args.trees)['tree_info']):
        lines += [f'static double wTree{i}(const int32_t* f) {{']+branch(t['tree_structure'],'    ')+['}']
    lines += ['static double wallDelta(const int32_t* f) {','    double delta=0;']
    lines += [f'    delta+=wTree{i}(f);' for i in range(args.trees)]
    lines += ['    return delta;','}']
    header=OUT/(args.name+'.wall.hpp');header.write_text('\n'.join(lines)+'\n')
    frozen=dict(candidate=args.name,model=args.model,model_sha256=sha(path),base=args.base,
                trees=args.trees,header_sha256=sha(header),bound_used=False)
    (OUT/(args.name+'_wall_frozen.json')).write_text(json.dumps(frozen,indent=2)+'\n')
    g=np.load(OUT/'geometry.npz');base=np.load(OUT/(args.base+'_prediction.npy'))
    x=make_features(g,base);ix=np.flatnonzero(x.landing_wall.to_numpy()>0)
    pred=base.copy();pred[ix]=np.maximum(0,np.floor(base[ix]+model.predict(x.iloc[ix],num_iteration=args.trees,num_threads=6)+.5)).astype(np.int32)
    np.save(OUT/(args.name+'_reference.npy'),pred)
    _,va,te,held=indices(g)
    frozen.update(valid=describe(g['y'][va],pred[va]),test=describe(g['y'][te],pred[te]),
                  position_assess=describe(g['y'][held],pred[held]),reference_sha256=sha(OUT/(args.name+'_reference.npy')),
                  caveat='Local base is deployed C++; wall correction is Python. A separate base-dot reference is required.')
    (REPO_ROOT/'docs'/(args.name+'_wall_export.json')).write_text(json.dumps(frozen,indent=2)+'\n')
    print(json.dumps(frozen,indent=2))


if __name__=='__main__':main()
